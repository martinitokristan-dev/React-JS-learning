let score = 50;

if (score >= 85) {
  console.log("Grade: A");
} else if (score >= 80) {
  console.log("Grade B");
} else if (score >= 75) {
  console.log("Grade: C");
} else if (score >= 70) {
  console.log("Grade: D");
} else if (score >= 65) {
  console.log("Grade: E");
} else if (score >= 60) {
  console.log("Grade: F");
} else {
  console.log("Invalid Score");
}
